-- COUNT EMPLOYEES PER DEPARTMENT.
SELECT D.DEPARTMENT_NAME,COUNT(E.EMP_ID)AS TOTAL_EMPLOYEES
FROM DEPARTMENTS D 
LEFT JOIN EMPLOYEES E 
ON D.DEPARTMENT_ID=E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME;

SELECT E.NAME,COUNT(P.PROJECT_ID)AS TOTAL_PROJECTS
FROM EMPLOYEES E   
LEFT JOIN PROJECTS P 
ON E.EMP_ID=P.EMP_ID
GROUP BY E.NAME;

SELECT D.DEPARTMENT_NAME,SUM(E.SALARY)AS TOTAL_SALARY
FROM DEPARTMENTS D 
LEFT JOIN EMPLOYEES E 
ON D.DEPARTMENT_ID=E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME;

SELECT D.DEPARTMENT_NAME,AVG(E.SALARY)AS TOTAL_SALARY
FROM DEPARTMENTS D 
LEFT JOIN EMPLOYEES E 
ON D.DEPARTMENT_ID=E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME;

SELECT D.DEPARTMENT_NAME,COUNT(E.EMP_ID)AS TOTAL_EMPLOYEES
FROM DEPARTMENTS D 
LEFT JOIN EMPLOYEES E 
ON D.DEPARTMENT_ID=E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
ORDER BY TOTAL_EMPLOYEES DESC;

SELECT D.DEPARTMENT_NAME,SUM(E.SALARY)AS TOTAL_SALARY
FROM DEPARTMENTS D 
LEFT JOIN EMPLOYEES E 
ON D.DEPARTMENT_ID=E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
ORDER BY TOTAL_SALARY ASC;

SELECT D.DEPARTMENT_NAME,COUNT(E.EMP_ID) AS TOTAL_EMPLOYEES
FROM DEPARTMENTS D
LEFT JOIN EMPLOYEES E
ON D.DEPARTMENT_ID=E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
HAVING COUNT(E.EMP_ID)>1
ORDER BY TOTAL_EMPLOYEES DESC;

SELECT D.DEPARTMENT_NAME,AVG(SALARY) AS TOTAL_SALARY
FROM DEPARTMENTS D
LEFT JOIN EMPLOYEES E
ON D.DEPARTMENT_ID=E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
HAVING AVG(SALARY)>40000
ORDER BY TOTAL_SALARY ASC;

